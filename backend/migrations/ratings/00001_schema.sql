-- +goose StatementBegin
DO $$
BEGIN
    -- Roles are per server: another database may have made them, and an
    -- owner without CREATEROLE can migrate once they exist.
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'ratings_read') THEN
        CREATE ROLE ratings_read NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'ratings_admin') THEN
        CREATE ROLE ratings_admin NOLOGIN;
    END IF;
END $$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE FUNCTION public.community_ranking() RETURNS bigint
    LANGUAGE sql STABLE
    AS $$
    SELECT ranking_id FROM rankings WHERE slug = 'community'
$$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE FUNCTION public.delete_run(id bigint) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
BEGIN
    DELETE FROM rating_runs r
    WHERE r.run_id = id AND r.deleting AND NOT r.protected
      AND NOT EXISTS (SELECT 1 FROM current_run c WHERE c.run_id = r.run_id);
    IF NOT FOUND THEN
        RAISE EXCEPTION 'run % is not marked for deletion, or is protected or current', id;
    END IF;
END
$$;
-- +goose StatementEnd

