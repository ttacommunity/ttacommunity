-- Badges admin makes and gives to players, shown beside their title at once
-- (no rating run). Who gave one is in admin_audit.

-- +goose Up
CREATE TABLE badges (
    badge_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label       text NOT NULL UNIQUE CHECK (length(label) BETWEEN 1 AND 16),
    description text NOT NULL DEFAULT ''
);
CREATE TABLE player_badges (
    player_name text   NOT NULL,
    badge_id    bigint NOT NULL REFERENCES badges ON DELETE CASCADE,
    PRIMARY KEY (player_name, badge_id)
);
GRANT SELECT, INSERT, UPDATE, DELETE ON badges, player_badges TO ratings_admin;
GRANT USAGE ON SEQUENCE badges_badge_id_seq TO ratings_admin;

-- +goose Down
REVOKE USAGE ON SEQUENCE badges_badge_id_seq FROM ratings_admin;
REVOKE SELECT, INSERT, UPDATE, DELETE ON badges, player_badges FROM ratings_admin;
DROP TABLE player_badges;
DROP TABLE badges;
